/**
 * docxBuilders.ts
 * Generates real .docx files using the `docx` library.
 * Each builder returns a Promise<Blob> with the correct MIME type.
 *
 * These replace the RTF builders which were renamed .docx but were
 * actually RTF format — causing "unreadable content" warnings in Word.
 */
import {
  Document,
  HeadingLevel,
  Packer,
  Paragraph,
  TextRun,
  AlignmentType,
  BorderStyle,
} from 'docx'

import type { NdaWizardData } from '../pages/user-dashboard/NdaWizardModal'
import type { EmploymentWizardData } from '../pages/user-dashboard/EmploymentWizardModal'
import type { PrivacyPolicyWizardData } from '../pages/user-dashboard/PrivacyPolicyWizardModal'
import type { FounderAgreementWizardData } from '../pages/user-dashboard/FounderAgreementWizardModal'
import type { ServiceAgreementWizardData } from '../pages/user-dashboard/ServiceAgreementWizardModal'

// ── Shared helpers ────────────────────────────────────────────────────────────

const fmtDate = (d: string | null) =>
  d ? new Date(d).toLocaleDateString('en-ZA') : new Date().toLocaleDateString('en-ZA')

const val = (v: string | undefined | null) => v || '—'
const yn  = (v: boolean) => (v ? 'Yes' : 'No')

/** Bold heading paragraph */
const h1 = (text: string) =>
  new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun({ text, bold: true, size: 28 })] })

const h2 = (text: string) =>
  new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun({ text, bold: true, size: 24 })] })

/** Label: value row */
const row = (label: string, value: string) =>
  new Paragraph({
    children: [
      new TextRun({ text: `${label}: `, bold: true }),
      new TextRun({ text: val(value) }),
    ],
    indent: { left: 360 },
  })

/** Thin horizontal separator */
const sep = () =>
  new Paragraph({
    border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: 'AAAAAA' } },
    spacing: { before: 120, after: 120 },
    children: [],
  })

/** Italic disclaimer footer */
const disclaimer = () =>
  new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 400 },
    children: [
      new TextRun({
        text: 'DISCLAIMER: This document is generated for reference purposes only. It does not constitute legal advice. Consult a qualified attorney.',
        italics: true,
        size: 18,
        color: '888888',
      }),
    ],
  })

const pack = (sections: Paragraph[]) =>
  Packer.toBlob(
    new Document({
      sections: [{ properties: {}, children: sections }],
      creator: 'The Startup Legal',
    }),
  )

// ── NDA ───────────────────────────────────────────────────────────────────────

export async function buildNdaDocx(data: NdaWizardData, completedAt: string | null): Promise<Blob> {
  const fmtAddr = (a: NdaWizardData['party_a']['address']) =>
    [a.street_number, a.building, a.street_name, a.suburb, a.city, a.province, a.postal_code, a.country].filter(Boolean).join(', ')

  return pack([
    h1('NON-DISCLOSURE AGREEMENT'),
    row('Date', fmtDate(completedAt)),
    row('Generated by', 'The Startup Legal'),
    sep(),
    h2('1. Parties'),
    row('Agreement Type', data.agreement_type),
    sep(),
    h2('Party A'),
    row('Type', data.party_a.entity_type),
    row('Legal Name', data.party_a.legal_name || data.party_a.full_names),
    row('Registration No.', data.party_a.reg_number),
    row('Address', fmtAddr(data.party_a.address)),
    row('Email', data.party_a.email),
    row('Signatory', `${data.party_a.signatory_name} (${data.party_a.signatory_capacity})`),
    sep(),
    h2('Party B'),
    row('Type', data.party_b.entity_type),
    row('Legal Name', data.party_b.legal_name || data.party_b.full_names),
    row('Registration No.', data.party_b.reg_number),
    row('Address', fmtAddr(data.party_b.address)),
    row('Email', data.party_b.email),
    row('Signatory', `${data.party_b.signatory_name} (${data.party_b.signatory_capacity})`),
    sep(),
    h2('2. Purpose & Scope'),
    row('Purpose', data.purpose),
    row('CI Definition', data.ci_definition),
    row('Must be marked confidential', yn(data.marking_required)),
    sep(),
    h2('3. Obligations'),
    row('Duration', `${data.duration_years} years, from ${data.duration_start}`),
    row('Return / Destroy', data.return_or_destroy),
    row('Archival copy', yn(data.archival_copy)),
    row('Non-solicitation', data.non_solicit ? `Yes (${data.non_solicit_months} months)` : 'No'),
    sep(),
    h2('4. Legal + Signing'),
    row('Governing Law', data.governing_law),
    row('Dispute Forum', data.dispute_forum),
    row('Signature Method', data.signature_method),
    row('Signing Order', data.signing_order),
    sep(),
    disclaimer(),
  ])
}

