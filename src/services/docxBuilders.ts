// ── Founder Agreement ─────────────────────────────────────────────────────────

export async function buildFounderAgreementDocx(d: FounderAgreementWizardData, completedAt: string | null): Promise<Blob> {
  const founderRows = d.founders.flatMap((f, i) => [
    h2(`Founder ${i + 1}`),
    row('Name', f.name),
    row('Email', f.email),
    row('Role', f.role),
    row('Equity', f.equity ? `${f.equity}%` : '—'),
  ])
  const sigRows = d.signatories.map((s, i) => row(`Signatory ${i + 1}`, `${val(s.name)} (${val(s.title)})`))
  return pack([
    h1("FOUNDERS' AGREEMENT & IP ASSIGNMENT"),
    row('Date', fmtDate(completedAt)),
    row('Generated by', 'The Startup Legal'),
    sep(),
    h2('1. Company Information'),
    row('Incorporated', d.isIncorporated),
    row('Company Name', d.companyName),
    row('Registration No.', d.registrationNumber),
    row('Registered Address', d.registeredAddress),
    sep(),
    h2('2. Founders'),
    ...founderRows,
    sep(),
    h2('3. Governance & Decision Making'),
    row('Decision Model', d.decisionMakingModel),
    row('Reserved Matters', d.reservedMatters.filter(r => r.trim()).join('; ')),
    row('Board Approval', d.boardApprovalRequirements),
    row('Founder Responsibilities', d.founderResponsibilities),
    sep(),
    h2('4. Vesting & Share Rules'),
    row('Vesting Enabled', d.vestingEnabled),
    ...(d.vestingEnabled === 'Yes' ? [row('Cliff Period', d.cliffPeriod), row('Vesting Period', d.vestingPeriod)] : []),
    row('Share Transfer Restrictions', d.shareTransferRestrictions),
    row('Buy-back Rights', d.buybackRights),
    row('Exit Rules', d.founderExitRules),
    sep(),
    h2('5. Intellectual Property'),
    row('Assign IP to Company', d.assignIpToCompany),
    row('Existing IP', d.hasExistingIp),
    ...(d.hasExistingIp === 'Yes' ? [row('IP Description', d.existingIpDescription), row('IP Assignment', d.existingIpAssignment)] : []),
    sep(),
    h2('6. Legal & Signing'),
    row('Confidentiality', d.confidentiality),
    row('Dispute Resolution', d.disputeResolution),
    row('Governing Law', d.governingLaw),
    row('Jurisdiction', d.jurisdiction),
    ...sigRows,
    sep(),
    disclaimer(),
  ])
}

