// ── Founder Agreement ─────────────────────────────────────────────────────────

export async function buildFounderAgreementDocx(d: FounderAgreementWizardData, completedAt: string | null): Promise<Blob> {
  const founderRows = d.founders.flatMap((f, i) => [
    h2(`Founder ${i + 1}`),
    row('Full names', f.fullNames),
    row('Identity number', f.idNumber),
    row('Role', f.role),
    row('Time commitment', f.commitment),
    row('Equity', f.equityPct ? `${f.equityPct}%` : '—'),
    row('Capital contributed', f.capital),
  ])
  const priorIpRows = d.priorIpNil
    ? [row('Pre-existing IP', 'Nothing to declare')]
    : d.priorIp.flatMap((p, i) => [
        h2(`Prior IP ${i + 1}`),
        row('Founder', p.founder),
        row('Description', p.description),
        row('Date created', p.dateCreated),
        row('Treatment', p.treatment),
      ])
  const digitalRows = d.digitalAssets.flatMap((a, i) => [
    h2(`Digital asset ${i + 1}`),
    row('Asset', a.asset),
    row('Current holder', a.currentHolder),
    row('Transfer date', a.transferDate),
  ])
  const sigRows = d.signatories.map((s, i) => row(`Signatory ${i + 1}`, `${val(s.name)} (${val(s.capacity)})`))
  return pack([
    h1("FOUNDERS' AGREEMENT & IP ASSIGNMENT"),
    row('Date', fmtDate(completedAt)),
    row('Generated by', 'The Startup Legal'),
    sep(),
    h2('1. Company Status'),
    row('Incorporated', d.isIncorporated),
    ...(d.isIncorporated === 'Yes'
      ? [row('Company Name', d.companyName)]
      : [row('Intended name', d.intendedName), row('Target incorporation', d.targetIncorporation)]),
    sep(),
    h2('2. Founders & Equity'),
    ...founderRows,
    sep(),
    h2('3. Vesting'),
    row('Vesting applies', d.vestingApplies),
    ...(d.vestingApplies === 'Yes' ? [
      row('Vesting period (months)', d.vestingMonths),
      row('Cliff (months)', d.cliffMonths),
      row('Frequency', d.vestingFrequency),
      row('Acceleration', d.acceleration),
      row('Good leaver', d.goodLeaver.join('; ')),
      row('Bad leaver consequence', d.badLeaverEffect),
    ] : []),
    sep(),
    h2('4. Decisions & Roles'),
    row('Decision model', d.decisionModel),
    row('Reserved matters', d.reservedMatters.join('; ')),
    ...(d.reservedMatters.includes('Take on debt above a threshold') ? [row('Debt threshold', d.debtThreshold)] : []),
    row('Removal process', d.removalProcess),
    row('Departure role', d.departureRole),
    sep(),
    h2('5. Intellectual Property'),
    row('IP assignment', 'Yes — assignment applies'),
    row('Assignment covers pre-incorporation work', d.ipPreIncorporation),
    ...priorIpRows,
    row('Publicly funded', d.publiclyFunded),
    row('Created while employed elsewhere', d.createdAtEmployer),
    ...digitalRows,
    sep(),
    h2('6. Protections & Legal'),
    row('Confidentiality', d.confidentiality),
    row('Non-solicitation', d.nonSolicit),
    row('Restraint of trade', d.restraint),
    ...(d.restraint === 'Yes' ? [row('Restraint duration (months)', d.restraintMonths), row('Restraint area', d.restraintArea)] : []),
    row('Deadlock mechanism', d.deadlock),
    row('Dispute resolution', d.disputeForum),
    row('Governing law', d.governingLaw),
    ...sigRows,
    sep(),
    disclaimer(),
  ])
}

